local S=KSStealth
local function label(parent,text,x,y,w,style)
  local t=parent:CreateFontString(nil,"OVERLAY",style or "GameFontNormal")
  t:SetPoint("TOPLEFT",parent,"TOPLEFT",x,y)
  t:SetWidth(w or 700)
  t:SetJustifyH("LEFT")
  t:SetText(text)
  return t
end
local function button(parent,text,x,y,w,fn)
  local b=CreateFrame("Button",nil,parent,"UIPanelButtonTemplate")
  b:SetSize(w,31);b:SetPoint("TOPLEFT",parent,"TOPLEFT",x,y)
  b:SetText(text);b:SetScript("OnClick",fn)
  return b
end
function S.BuildPage(parent)
  local db=S:Store()
  label(parent,"|cffffd87aKS Stealth - Resource HUD|r",20,-18,760,"GameFontNormalLarge")
  label(parent,"Shows your combo points above every visible target nameplate that the client exposes.",20,-55,770)
  label(parent,"This is an informational display, not a finisher selector or rotation helper.",20,-85,770)
  local status=label(parent,"",20,-385,775)
  local classOkay=S:IsSupportedClass()
  label(parent,classOkay and "Class: Rogue / Druid supported" or "Class: enable on a Rogue or Druid to see combo points",20,-126,760)
  local enabled=button(parent,"",20,-172,225,function()end)
  local scaleLabel=label(parent,"",275,-177,210)
  button(parent,"Smaller",275,-205,105,function()
    local ok,reason=S:SetScale(S:Store().scale-.1)
    status:SetText(ok and "Scale updated" or reason)
    scaleLabel:SetText(string.format("Size: %.1fx",S:Store().scale))
  end)
  button(parent,"Larger",391,-205,105,function()
    local ok,reason=S:SetScale(S:Store().scale+.1)
    status:SetText(ok and "Scale updated" or reason)
    scaleLabel:SetText(string.format("Size: %.1fx",S:Store().scale))
  end)
  local offsetLabel=label(parent,"",275,-268,260)
  button(parent,"Lower",275,-295,105,function()
    local ok,reason=S:SetOffset(S:Store().offsetY-2)
    status:SetText(ok and "Position updated" or reason)
    offsetLabel:SetText("Vertical offset: "..S:Store().offsetY)
  end)
  button(parent,"Higher",391,-295,105,function()
    local ok,reason=S:SetOffset(S:Store().offsetY+2)
    status:SetText(ok and "Position updated" or reason)
    offsetLabel:SetText("Vertical offset: "..S:Store().offsetY)
  end)
  local function redraw()
    enabled:SetText(S:Store().nameplates and "Nameplate pips: ON" or "Nameplate pips: OFF")
    scaleLabel:SetText(string.format("Size: %.1fx",S:Store().scale))
    offsetLabel:SetText("Vertical offset: "..S:Store().offsetY)
  end
  enabled:SetScript("OnClick",function()
    local ok,reason=S:SetNameplates(not S:Store().nameplates)
    status:SetText(ok and "Visibility updated" or reason)
    redraw()
  end)
  redraw()
  label(parent,"Requires enemy nameplates and visible nameplate unit tokens.",20,-442,765)
  label(parent,"Forever secret values are sent directly into UI bars; no combat decisions or point comparisons.",20,-472,765)
  label(parent,"Unverified until tested in Forever. This does not discover off-screen enemies or true spell range.",20,-507,765)
end
