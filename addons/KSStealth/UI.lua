-- KS Stealth: Guilty Forever-style settings cards, with explicit idle HUD preview.
-- All gameplay and saved settings still live in Stealth.lua/HUD.lua.
local S=KSStealth
local FONT=STANDARD_TEXT_FONT or "Fonts\\FRIZQT__.TTF"
local GOLD="|cffffd87a"
local MUTED="|cff9fb4ad"
local GREEN="|cff8be2bb"
local function label(parent,words,x,y,w,size)
 local t=parent:CreateFontString(nil,"OVERLAY",size=="title" and "GameFontNormalLarge" or "GameFontNormal")
 t:SetPoint("TOPLEFT",parent,"TOPLEFT",x,y)
 t:SetWidth(w);t:SetJustifyH("LEFT");t:SetText(words)
 if t.SetFont then pcall(t.SetFont,t,FONT,size=="title" and 24 or size=="small" and 15 or 18,"") end
 return t
end
local function panel(parent,x,y,w,h)
 local p=CreateFrame("Frame",nil,parent,"BackdropTemplate")
 p:SetPoint("TOPLEFT",parent,"TOPLEFT",x,y);p:SetSize(w,h)
 if p.SetBackdrop then
  p:SetBackdrop({bgFile="Interface\\Buttons\\WHITE8X8",edgeFile="Interface\\Buttons\\WHITE8X8",edgeSize=1})
  if p.SetBackdropColor then p:SetBackdropColor(.075,.09,.115,.96) end
  if p.SetBackdropBorderColor then p:SetBackdropBorderColor(.48,.35,.19,.85) end
 end
 return p
end
local function button(parent,words,x,y,w,fn)
 local b=CreateFrame("Button",nil,parent,"UIPanelButtonTemplate")
 b:SetPoint("TOPLEFT",parent,"TOPLEFT",x,y);b:SetSize(w,40)
 b:SetText(words);b:SetScript("OnClick",fn)
 if b.GetFontString then
  local t=b:GetFontString()
  if t and t.SetFont then pcall(t.SetFont,t,FONT,16,"") end
 end
 return b
end
function S.BuildPage(parent)
 local status=label(parent,"",22,-623,893,"small")
 label(parent,GOLD.."KS STEALTH  /  COMBO POINTS|r",23,-19,900,"title")
 label(parent,MUTED.."Configure two independent displays: nameplate pips and your movable HUD.|r",23,-59,884)
 local np=panel(parent,23,-106,896,182)
 label(np,GOLD.."NAMEPLATE COMBO POINTS|r",18,-16,780,"title")
 label(np,"Five points above visible nameplates. Independent of your movable HUD.",18,-54,836)
 local nameplate=button(np,"",18,-107,251,function()end)
 local scaleText=label(np,"",295,-87,280)
 local offsetText=label(np,"",590,-87,260)
 button(np,"- Size",291,-127,125,function()
  local ok,why=S:SetScale(S:Store().scale-.1)
  status:SetText(ok and "Nameplate pip size reduced." or why)
  scaleText:SetText(string.format("Size %.1fx",S:Store().scale))
 end)
 button(np,"+ Size",420,-127,125,function()
  local ok,why=S:SetScale(S:Store().scale+.1)
  status:SetText(ok and "Nameplate pip size increased." or why)
  scaleText:SetText(string.format("Size %.1fx",S:Store().scale))
 end)
 button(np,"Lower",591,-127,126,function()
  local ok,why=S:SetOffset(S:Store().offsetY-2)
  status:SetText(ok and "Nameplate pips moved lower." or why)
  offsetText:SetText("Offset "..S:Store().offsetY)
 end)
 button(np,"Higher",724,-127,126,function()
  local ok,why=S:SetOffset(S:Store().offsetY+2)
  status:SetText(ok and "Nameplate pips moved higher." or why)
  offsetText:SetText("Offset "..S:Store().offsetY)
 end)
 local hud=panel(parent,23,-301,896,310)
 label(hud,GOLD.."MOVABLE COMBO POINT HUD|r",18,-16,820,"title")
 label(hud,"No target needed: show five empty pips, drag them, then click Done / Lock.",18,-57,843)
 local show=button(hud,"SHOW HUD / MOVE",18,-101,245,function()end)
 local done=button(hud,"DONE / LOCK",277,-101,209,function()end)
 local toggle=button(hud,"",499,-101,180,function()end)
 local reset=button(hud,"Reset position",693,-101,184,function()
  local ok,why=S:ResetHUDPosition()
  status:SetText(ok and "HUD reset to its default position." or why)
 end)
 local lock=button(hud,"",18,-156,245,function()end)
 local hudScale=label(hud,"",291,-165,185)
 button(hud,"- HUD size",501,-156,176,function()
  local ok,why=S:SetHUDScale(S:HUDSettings().hudScale-.1)
  status:SetText(ok and "HUD resized." or why)
  hudScale:SetText(string.format("HUD: %.1fx",S:HUDSettings().hudScale))
 end)
 button(hud,"+ HUD size",694,-156,183,function()
  local ok,why=S:SetHUDScale(S:HUDSettings().hudScale+.1)
  status:SetText(ok and "HUD resized." or why)
  hudScale:SetText(string.format("HUD: %.1fx",S:HUDSettings().hudScale))
 end)
 label(hud,GREEN.."POSITION MODE:|r  drag the gold COMBO POINTS label to move all five pips.",18,-221,846)
 label(hud,MUTED.."The preview remains visible when idle until locked. Position and scale save per character.|r",18,-255,847,"small")
 local function redraw()
  local db=S:HUDSettings()
  nameplate:SetText(S:Store().nameplates and "Nameplate pips: ON" or "Nameplate pips: OFF")
  scaleText:SetText(string.format("Size %.1fx",S:Store().scale))
  offsetText:SetText("Offset "..S:Store().offsetY)
  toggle:SetText(db.hudEnabled and "HUD: ON" or "HUD: OFF")
  lock:SetText(db.hudLocked and "Unlock / move HUD" or "Lock HUD position")
  show:SetText(db.hudLocked and "SHOW HUD / MOVE" or "HUD VISIBLE / MOVING")
  hudScale:SetText(string.format("HUD: %.1fx",db.hudScale))
 end
 nameplate:SetScript("OnClick",function()
  local ok,why=S:SetNameplates(not S:Store().nameplates)
  status:SetText(ok and "Nameplate display updated." or why);redraw()
 end)
 show:SetScript("OnClick",function()
  local ok,why=S:ShowHUDForPositioning()
  status:SetText(ok and "Five preview pips shown. Drag the gold label; Done / Lock when finished." or why)
  redraw()
 end)
 done:SetScript("OnClick",function()
  local ok,why=S:FinishHUDPositioning()
  status:SetText(ok and "Position saved. HUD locked; it shows again when targeting." or why)
  redraw()
 end)
 toggle:SetScript("OnClick",function()
  local ok,why=S:SetHUDEnabled(not S:HUDSettings().hudEnabled)
  status:SetText(ok and "HUD visibility changed." or why);redraw()
 end)
 lock:SetScript("OnClick",function()
  local ok,why=S:SetHUDLocked(not S:HUDSettings().hudLocked)
  status:SetText(ok and (S:HUDSettings().hudLocked and "HUD locked." or "Preview shown; drag the HUD now.") or why)
  redraw()
 end)
 redraw()
 button(parent,"Browse Talent Impacts",23,-651,291,function()KoolSupport:ShowPage("stealth_talents")end)
 label(parent,MUTED.."Changes are blocked in combat. Combo points remain secret-safe native StatusBars.|r",333,-663,595,"small")
end
