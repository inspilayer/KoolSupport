-- KS Stealth settings: native nameplate pips + independently movable combo HUD.
local S=KSStealth
local GOLD="|cffffd87a"
local MUTED="|cff9fb4ad"
local function label(parent,text,x,y,w,style)
  local t=parent:CreateFontString(nil,"OVERLAY",style or "GameFontNormal")
  t:SetPoint("TOPLEFT",parent,"TOPLEFT",x,y)
  t:SetWidth(w or 700)
  t:SetJustifyH("LEFT")
  t:SetText(text)
  return t
end
local function button(parent,text,x,y,w,fn)
  local b=CreateFrame("Button",nil,parent,"UIPanelButtonTemplate")
  b:SetSize(w,31)
  b:SetPoint("TOPLEFT",parent,"TOPLEFT",x,y)
  b:SetText(text)
  b:SetScript("OnClick",fn)
  return b
end
function S.BuildPage(parent)
  local db=S:HUDSettings()
  label(parent,GOLD.."KS Stealth - Combo Points|r",20,-18,760,"GameFontNormalLarge")
  label(parent,"Two independent displays: nameplate pips and a movable on-screen combo tracker.",20,-53,770)
  label(parent,S:IsSupportedClass() and "Class: Druid / Rogue supported" or
    "Combo points are available on Druid / Rogue.",20,-87,760)
  local status=label(parent,"",20,-450,775,"GameFontHighlightSmall")

  label(parent,GOLD.."Nameplate combo points|r",20,-124,750,"GameFontNormalLarge")
  local nameplate=button(parent,"",20,-158,218,function()end)
  local scaleText=label(parent,"",270,-158,205)
  local offsetText=label(parent,"",515,-158,256)
  button(parent,"Smaller",270,-195,103,function()
    local ok,reason=S:SetScale(S:Store().scale-.1)
    status:SetText(ok and "Nameplate pips resized." or reason)
    scaleText:SetText(string.format("Size: %.1fx",S:Store().scale))
  end)
  button(parent,"Larger",380,-195,103,function()
    local ok,reason=S:SetScale(S:Store().scale+.1)
    status:SetText(ok and "Nameplate pips resized." or reason)
    scaleText:SetText(string.format("Size: %.1fx",S:Store().scale))
  end)
  button(parent,"Lower",515,-195,106,function()
    local ok,reason=S:SetOffset(S:Store().offsetY-2)
    status:SetText(ok and "Nameplate pips moved." or reason)
    offsetText:SetText("Offset: "..S:Store().offsetY)
  end)
  button(parent,"Higher",629,-195,106,function()
    local ok,reason=S:SetOffset(S:Store().offsetY+2)
    status:SetText(ok and "Nameplate pips moved." or reason)
    offsetText:SetText("Offset: "..S:Store().offsetY)
  end)

  label(parent,GOLD.."Movable combo-point HUD|r",20,-264,750,"GameFontNormalLarge")
  local show=button(parent,"",20,-303,220,function()end)
  local lock=button(parent,"",254,-303,220,function()end)
  button(parent,"Reset position",491,-303,204,function()
    local ok,reason=S:ResetHUDPosition()
    status:SetText(ok and "HUD returned to its default position." or reason)
  end)
  local hudScaleText=label(parent,"",20,-363,232)
  button(parent,"HUD smaller",254,-354,145,function()
    local ok,reason=S:SetHUDScale(S:HUDSettings().hudScale-.1)
    status:SetText(ok and "HUD size updated." or reason)
    hudScaleText:SetText(string.format("HUD size: %.1fx",S:HUDSettings().hudScale))
  end)
  button(parent,"HUD larger",412,-354,145,function()
    local ok,reason=S:SetHUDScale(S:HUDSettings().hudScale+.1)
    status:SetText(ok and "HUD size updated." or reason)
    hudScaleText:SetText(string.format("HUD size: %.1fx",S:HUDSettings().hudScale))
  end)
  label(parent,MUTED.."Unlock, then drag the gold COMBO POINTS label; lock when positioned. Works with nameplate pips off.|r",
    20,-406,778,"GameFontHighlightSmall")
  label(parent,MUTED.."HUD shows on a selected target; unlocking shows empty pips for positioning.|r",
    20,-425,773,"GameFontHighlightSmall")

  local function redraw()
    local settings=S:HUDSettings()
    nameplate:SetText(S:Store().nameplates and "Nameplate pips: ON" or "Nameplate pips: OFF")
    scaleText:SetText(string.format("Size: %.1fx",S:Store().scale))
    offsetText:SetText("Offset: "..S:Store().offsetY)
    show:SetText(settings.hudEnabled and "HUD: ON" or "HUD: OFF")
    lock:SetText(settings.hudLocked and "Unlock / move HUD" or "Lock HUD position")
    hudScaleText:SetText(string.format("HUD size: %.1fx",settings.hudScale))
  end
  nameplate:SetScript("OnClick",function()
    local ok,reason=S:SetNameplates(not S:Store().nameplates)
    status:SetText(ok and "Nameplate visibility updated." or reason)
    redraw()
  end)
  show:SetScript("OnClick",function()
    local ok,reason=S:SetHUDEnabled(not S:HUDSettings().hudEnabled)
    status:SetText(ok and "HUD visibility updated." or reason)
    redraw()
  end)
  lock:SetScript("OnClick",function()
    local ok,reason=S:SetHUDLocked(not S:HUDSettings().hudLocked)
    status:SetText(ok and (S:HUDSettings().hudLocked and "HUD locked in place." or
      "HUD unlocked. Drag the gold label to reposition it.") or reason)
    redraw()
  end)
  redraw()

  button(parent,"Browse Talent Impacts",20,-496,237,function()
    KoolSupport:ShowPage("stealth_talents")
  end)
  label(parent,"Talent previews are optional and read-only.",276,-502,490)
  label(parent,MUTED.."All combo-point values pass directly to native UI bars; secret values are never compared in Lua.|r",
    20,-543,785,"GameFontHighlightSmall")
  label(parent,MUTED.."Position, scale and lock state persist per character; changes are blocked during combat.|r",
    20,-566,785,"GameFontHighlightSmall")
end
